const { sendWhatsApp: mockSendWhatsApp } = require('../mocks/twilio.mock');
const { USE_MOCKS } = require('../mocks');

async function sendRealTwilioWhatsApp(to, message) {
  const accountSid = process.env.TWILIO_ACCOUNT_SID;
  const authToken = process.env.TWILIO_AUTH_TOKEN;
  const fromNumber = process.env.TWILIO_WHATSAPP_FROM || '+14155238886'; // Twilio sandbox default

  if (!accountSid || !authToken) {
    throw new Error('Twilio credentials not configured');
  }

  const endpoint = `https://api.twilio.com/2010-04-01/Accounts/${accountSid}/Messages.json`;
  const authHeader = 'Basic ' + Buffer.from(`${accountSid}:${authToken}`).toString('base64');

  const params = new URLSearchParams();
  params.append('From', fromNumber.startsWith('whatsapp:') ? fromNumber : `whatsapp:${fromNumber}`);
  params.append('To', to.startsWith('whatsapp:') ? to : `whatsapp:${to}`);
  params.append('Body', message);

  const res = await fetch(endpoint, {
    method: 'POST',
    headers: {
      'Authorization': authHeader,
      'Content-Type': 'application/x-www-form-urlencoded'
    },
    body: params.toString()
  });

  const data = await res.json();
  if (!res.ok) {
    throw new Error(data.message || 'Twilio WhatsApp dispatch failed');
  }
  return { status: 'sent', sid: data.sid, timestamp: new Date().toISOString() };
}

async function notifyAuditCompletion(clientId, pdfPath, score, clientPhone) {
  const recipient = clientPhone || '+91 98200 12345';
  const baseUrl = process.env.NEXT_PUBLIC_APP_URL || 'http://localhost:3000';
  const message = `🎉 Your SEO Audit Report is ready!\n\n📊 Health Score: ${score}/100\n📄 Download PDF Report: ${baseUrl}${pdfPath}\n\nGenerated by SEO Automation Engine.`;

  const hasTwilioCreds = Boolean(process.env.TWILIO_ACCOUNT_SID && process.env.TWILIO_AUTH_TOKEN);

  if (!USE_MOCKS && hasTwilioCreds) {
    try {
      console.log(`[Twilio WhatsApp] Sending live message to ${recipient}...`);
      const result = await sendRealTwilioWhatsApp(recipient, message);
      console.log(`[Twilio WhatsApp] ✅ Message delivered. SID: ${result.sid}`);
      return { success: true, result, recipient, isLive: true };
    } catch (err) {
      console.warn(`[Twilio WhatsApp] Live dispatch failed (${err.message}). Falling back to mock.`);
    }
  }

  // Console log mock (Section 2.3 specification)
  const mockResult = await mockSendWhatsApp(clientId, pdfPath, score);
  return {
    success: true,
    result: mockResult,
    recipient,
    isLive: false
  };
}

module.exports = { notifyAuditCompletion, sendRealTwilioWhatsApp };
