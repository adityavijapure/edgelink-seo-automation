const { sendWhatsApp: mockSendWhatsApp } = require('../mocks/twilio.mock');
const { USE_MOCKS } = require('../mocks');

function formatPhoneNumber(phone) {
  if (!phone) return '+919820012345';
  let clean = phone.replace(/[^0-9+]/g, '');
  if (clean.length === 10) {
    clean = '+91' + clean;
  }
  if (!clean.startsWith('+')) {
    clean = '+' + clean;
  }
  return clean;
}

async function sendRealTwilioWhatsApp(to, message, mediaUrl) {
  const accountSid = process.env.TWILIO_ACCOUNT_SID;
  const authToken = process.env.TWILIO_AUTH_TOKEN;
  const rawFrom = process.env.TWILIO_WHATSAPP_FROM || '+14155238886';

  let cleanFrom = rawFrom.replace(/whatsapp:/i, '').replace(/[^0-9+]/g, '');
  if (cleanFrom.startsWith('++')) cleanFrom = cleanFrom.replace(/^\++/, '+');
  if (!cleanFrom.startsWith('+')) cleanFrom = '+' + cleanFrom;

  let cleanTo = to.replace(/whatsapp:/i, '').replace(/[^0-9+]/g, '');
  if (cleanTo.startsWith('++')) cleanTo = cleanTo.replace(/^\++/, '+');
  if (!cleanTo.startsWith('+')) cleanTo = '+' + cleanTo;

  if (!accountSid || !authToken) {
    throw new Error('Twilio credentials not configured');
  }

  const endpoint = `https://api.twilio.com/2010-04-01/Accounts/${accountSid}/Messages.json`;
  const authHeader = 'Basic ' + Buffer.from(`${accountSid}:${authToken}`).toString('base64');

  const params = new URLSearchParams();
  params.append('From', `whatsapp:${cleanFrom}`);
  params.append('To', `whatsapp:${cleanTo}`);
  params.append('Body', message);
  if (mediaUrl && /^https?:\/\//i.test(mediaUrl) && !mediaUrl.includes('localhost')) {
    params.append('MediaUrl', mediaUrl);
  }

  const res = await fetch(endpoint, {
    method: 'POST',
    headers: {
      'Authorization': authHeader,
      'Content-Type': 'application/x-www-form-urlencoded'
    },
    body: params.toString()
  });

  const data = await res.json();
  if (!res.ok) {
    if (data.code === 21654) {
      console.warn(`[Twilio Notice] WhatsApp template required or conversation window closed. Send 'Hi' on WhatsApp from ${cleanTo} to ${cleanFrom} to open a 24-hr session.`);
    }
    throw new Error(data.message || `Twilio dispatch failed (${data.code})`);
  }
  return { status: 'sent', sid: data.sid, timestamp: new Date().toISOString() };
}

async function notifyAuditCompletion(clientId, pdfPath, score, clientPhone, clientEmail) {
  const recipient = formatPhoneNumber(clientPhone || '+919820012345');
  const baseUrl = process.env.NEXT_PUBLIC_APP_URL || 'http://localhost:3000';
  const fullPdfUrl = `${baseUrl}${pdfPath}`;
  
  const message = `🎉 Your SEO Audit Report is ready!\n\n📊 Health Score: ${score}/100\n📄 Download PDF Report: ${fullPdfUrl}\n\nClient: ${clientId}\nGenerated by SEO Automation Engine.`;

  const cleanDigits = recipient.replace(/[^0-9]/g, '');
  const whatsappShareUrl = `https://api.whatsapp.com/send?phone=${cleanDigits}&text=${encodeURIComponent(message)}`;
  
  const recipientEmail = clientEmail || 'rahul@example-dental-clinic.com';
  const emailSubject = `SEO Audit Report Ready (Score: ${score}/100) - ${clientId}`;
  const emailBody = `Hi,\n\nYour comprehensive SEO audit report is ready.\n\n📊 Health Score: ${score}/100\n📄 Executive PDF Report: ${fullPdfUrl}\n\nGenerated by SEO Pulse Automation Engine.`;
  const mailtoUrl = `mailto:${encodeURIComponent(recipientEmail)}?subject=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(emailBody)}`;

  const hasTwilioCreds = Boolean(process.env.TWILIO_ACCOUNT_SID && process.env.TWILIO_AUTH_TOKEN);

  // If USE_MOCKS is false and credentials are provided, attempt real Twilio dispatch
  if (!USE_MOCKS && hasTwilioCreds) {
    try {
      console.log(`[Twilio WhatsApp] Sending live PDF alert to ${recipient}...`);
      const result = await sendRealTwilioWhatsApp(recipient, message, fullPdfUrl);
      console.log(`[Twilio WhatsApp] ✅ Message delivered to ${recipient}. SID: ${result.sid}`);
      return { 
        success: true, 
        result, 
        recipient, 
        recipientPhone: recipient,
        recipientEmail,
        isLive: true,
        whatsappShareUrl,
        mailtoUrl,
        pdfUrl: fullPdfUrl,
        message
      };
    } catch (err) {
      console.warn(`[Twilio WhatsApp] Live dispatch failed (${err.message}). Falling back to mock.`);
    }
  }

  // Console log mock for WhatsApp (Section 2.3 specification)
  const mockResult = await mockSendWhatsApp(clientId, pdfPath, score);

  // Console log mock for Email (Section 1.1 & Section 3.1 specification)
  console.log('[MOCK EMAIL]    → Recipient:  ' + recipientEmail);
  console.log('[MOCK EMAIL]    → Subject:    ' + emailSubject);
  console.log('[MOCK EMAIL]    → Attachment: ' + pdfPath);

  return {
    success: true,
    result: mockResult,
    recipient,
    recipientPhone: recipient,
    recipientEmail,
    isLive: false,
    whatsappShareUrl,
    mailtoUrl,
    pdfUrl: fullPdfUrl,
    message
  };
}

module.exports = { notifyAuditCompletion, sendRealTwilioWhatsApp, formatPhoneNumber };
